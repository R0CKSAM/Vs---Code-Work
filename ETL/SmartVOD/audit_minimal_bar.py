from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path('ETL/SmartVOD');checks=[];errors=[]
def check(n,ok):
 assert ok,n
 checks.append(n)
with sync_playwright() as p:
 b=p.chromium.launch(channel='msedge',headless=True);page=b.new_page(viewport={'width':1440,'height':1000},accept_downloads=True)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8766');page.wait_for_function("document.getElementById('status').textContent.includes('matched records')",timeout=60000)
 check('Branding restored',page.locator('.compact-brand').is_visible())
 check('Only Title in basic filters',page.locator('#filters .filter-trigger').count()==1)
 check('Ten remaining filters in drawer',page.locator('#advancedFilters .filter-trigger').count()==10)
 check('Actions absent from top',page.locator('.master-filters #apply,.master-filters #reset,.master-filters #export').count()==0)
 page.locator('#rangeTitle').click();page.locator('#weekDateRange').click();page.locator('#applyDateRange').click()
 page.wait_for_function("!document.getElementById('apply').disabled",timeout=60000)
 check('Dates apply automatically',page.evaluate("applied.start===document.getElementById('start').value&&applied.end===document.getElementById('end').value"))
 page.locator('#filter-title').click();page.locator('#options input').first.wait_for();page.locator('#options input').first.check();page.locator('#done').click()
 page.wait_for_function("!document.getElementById('apply').disabled",timeout=60000)
 check('Title applies automatically on Done',page.evaluate('applied.filters.title.length===1'))
 page.locator('#advancedToggle').click();page.wait_for_timeout(250)
 check('Reset export and apply accessible',all(page.locator('#'+i).is_visible() for i in ['reset','export','apply']))
 page.locator('#filter-device_type').click();page.locator('#options input').first.wait_for();page.locator('#options input').first.check();page.locator('#done').click()
 check('Moved filters included in badge',page.locator('#advancedCount').inner_text()=='1')
 page.locator('#apply').click();page.wait_for_function("document.getElementById('advancedDrawer').getAttribute('aria-hidden')==='true'",timeout=60000)
 check('Title and advanced filters combined',page.evaluate('applied.filters.title.length===1&&applied.filters.device_type.length===1'))
 check('Metrics agree with API',page.evaluate("async()=>{const d=await(await request('/api/query',applied)).json();return document.getElementById('hours').textContent===fmt(d.kpi.hours,2)}"))
 page.locator('#advancedToggle').click();page.wait_for_timeout(250)
 with page.expect_download() as download:page.locator('#export').click()
 check('CSV export in drawer',download.value.suggested_filename.endswith('.csv'))
 page.locator('#timeStart').fill('');page.locator('#timeStart').dispatch_event('change');page.locator('#apply').click();page.locator('#drawerError').wait_for()
 check('Invalid input feedback visible inside drawer',page.locator('#drawerError').inner_text()=='Choose both time values.')
 page.locator('#reset').click();page.wait_for_function("!document.getElementById('apply').disabled",timeout=60000)
 check('Reset still clears all filters',page.evaluate('Object.values(applied.filters).every(x=>!x.length)'))
 page.locator('#apply').click();page.wait_for_function("document.getElementById('advancedDrawer').getAttribute('aria-hidden')==='true'",timeout=60000)
 for width in [1920,1440,1024,768,600,390,320]:
  page.set_viewport_size({'width':width,'height':900});page.wait_for_timeout(150)
  boxes=page.locator('.compact-brand,.range-field,#filters .field,#advancedToggle').evaluate_all('(nodes)=>nodes.map(e=>e.getBoundingClientRect().toJSON())')
  check(f'{width} one bar row',max(r['y']+r['height']/2 for r in boxes)-min(r['y']+r['height']/2 for r in boxes)<2)
  check(f'{width} no page overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
  check(f'{width} text contained',page.evaluate("[...document.querySelectorAll('#rangeTitle,#filter-title,#advancedToggle')].every(e=>e.scrollWidth<=e.clientWidth+1&&e.scrollHeight<=e.clientHeight+1)"))
  page.locator('#advancedToggle').click();page.wait_for_timeout(250)
  check(f'{width} actions reachable',page.locator('#apply').is_visible() and page.locator('#export').is_visible())
  page.keyboard.press('Escape');page.wait_for_timeout(250)
  if width in [1440,390]:page.screenshot(path=str(ROOT/f'audit/minimal_bar_{width}.png'))
 check('No browser errors',not errors);b.close()
(ROOT/'audit/minimal_bar.json').write_text(json.dumps({'passed':True,'checks':checks,'errors':errors},indent=2))
print('PASS',len(checks),'checks')
