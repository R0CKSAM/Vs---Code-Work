from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path('ETL/SmartVOD');checks=[];errors=[]
def check(name,ok):
 assert ok,name
 checks.append(name)
with sync_playwright() as p:
 browser=p.chromium.launch(channel='msedge',headless=True)
 page=browser.new_page(viewport={'width':1920,'height':1080},accept_downloads=True)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8766/')
 page.wait_for_function("document.getElementById('status').textContent.includes('matched records')",timeout=60000)
 check('No masthead or promotional hero',page.locator('body > header').count()==0 and page.locator('h1').count()==0)
 check('Four basic dimension filters',page.locator('#filters .filter-trigger').count()==4)
 check('Seven advanced dimension filters',page.locator('#advancedFilters .filter-trigger').count()==7)
 check('Basic filters first on screen',page.locator('.master-filters').bounding_box()['y']<25)
 page.locator('#advancedToggle').click()
 page.wait_for_timeout(250)
 check('Desktop drawer quarter width',abs(page.locator('#advancedDrawer').bounding_box()['width']-480)<2)
 check('Main content inert while drawer open',page.locator('main').evaluate('(e)=>e.inert'))
 page.locator('#closeAdvanced').focus();page.keyboard.press('Shift+Tab')
 check('Reverse Tab wraps within drawer',page.locator('#applyAdvanced').evaluate('(e)=>document.activeElement===e'))
 page.keyboard.press('Tab')
 check('Tab wraps to drawer close',page.locator('#closeAdvanced').evaluate('(e)=>document.activeElement===e'))
 page.locator('#filter-isp').click();page.locator('#options .option').first.wait_for()
 page.locator('#search').fill('Unknown')
 page.wait_for_timeout(500)
 check('Advanced search updates options',page.locator('#search').input_value()=='Unknown')
 page.keyboard.press('Escape')
 check('Escape closes nested picker only',page.locator('#picker').is_hidden() and page.locator('#advancedDrawer').get_attribute('aria-hidden')=='false')
 page.locator('#filter-category').click();page.locator('#options input').first.wait_for();page.locator('#options input').first.check();page.locator('#done').click()
 check('Advanced selected badge',page.locator('#advancedCount').inner_text()=='1')
 page.locator('#timeStart').fill('09:00');page.locator('#timeStart').dispatch_event('change')
 page.locator('#timeEnd').fill('21:00');page.locator('#timeEnd').dispatch_event('change')
 page.locator('#applyAdvanced').click()
 page.wait_for_function("document.getElementById('advancedDrawer').getAttribute('aria-hidden')==='true'",timeout=60000)
 check('Apply closes drawer and updates results','09:00' in page.locator('#status').inner_text())
 check('Advanced selection persists',page.evaluate("applied.filters.category.length===1 && applied.timeStart==='09:00'"))
 page.locator('#filter-region').click();page.locator('#options input').first.wait_for();page.locator('#options input').first.check();page.locator('#done').click();page.locator('#apply').click()
 page.wait_for_function("!document.getElementById('apply').disabled",timeout=60000)
 check('Basic and advanced filters combine',page.evaluate("applied.filters.category.length===1 && applied.filters.region.length===1"))
 check('Basic+advanced result agrees with API',page.evaluate("async()=>{const d=await(await request('/api/query',applied)).json();return document.getElementById('hours').textContent===fmt(d.kpi.hours,2)}"))
 page.locator('#advancedToggle').click()
 page.locator('.saved-menu summary').click();page.locator('#savedName').fill('Drawer audit');page.locator('#saveView').click()
 check('Saved views accessible in drawer','saved' in page.locator('#viewMessage').inner_text())
 page.locator('#closeAdvanced').click()
 with page.expect_download() as download:page.locator('#export').click()
 check('CSV export works',download.value.suggested_filename.endswith('.csv'))
 page.locator('#reset').click();page.wait_for_function("!document.getElementById('apply').disabled",timeout=60000)
 check('Reset clears both sets and times',page.evaluate("Object.values(applied.filters).every(v=>v.length===0)&&applied.timeStart==='00:00'&&applied.timeEnd==='23:59'"))
 for width in [1920,1440,1024,768,390,320]:
  page.set_viewport_size({'width':width,'height':900});page.wait_for_timeout(150)
  check(f'{width}px no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
  page.locator('#advancedToggle').click();page.wait_for_timeout(250)
  box=page.locator('#advancedDrawer').bounding_box()
  check(f'{width}px drawer fits',box['x']>=-1 and box['x']+box['width']<=width+1)
  check(f'{width}px focus stays in drawer',page.locator('#closeAdvanced').evaluate('(e)=>document.activeElement===e'))
  if width in [1440,390]:page.screenshot(path=str(ROOT/f'audit/filter_drawer_{width}.png'))
  page.keyboard.press('Escape')
  check(f'{width}px close restores focus',page.locator('#advancedToggle').evaluate('(e)=>document.activeElement===e'))
 page.set_viewport_size({'width':1440,'height':1000});page.wait_for_timeout(300);page.screenshot(path=str(ROOT/'audit/quick_filters_redesign.png'),full_page=True)
 check('No browser JS errors',not errors)
 browser.close()
(ROOT/'audit/filter_drawer.json').write_text(json.dumps({'passed':True,'checks':checks,'errors':errors},indent=2))
print('PASS',len(checks),'checks')
