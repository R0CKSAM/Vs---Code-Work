"""Panel layout browser checks: pointer, keyboard, persistence, refresh, reset."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent;checks=[]
def check(name,ok):
    assert ok,name
    checks.append(name)
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000});errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:8766/')
    page.wait_for_function("applied!==null&&!document.getElementById('apply').disabled",timeout=120000)
    check('All 17 panels editable',page.locator('.layout-tile').count()==17)
    check('Handles hidden by default',not page.locator('.layout-handle').first.is_visible())
    body=page.evaluate('JSON.stringify(applied)');hours=page.locator('#hours').inner_text()
    page.locator('#advancedToggle').click();page.locator('#layoutToggle').click()
    check('Edit mode visible',page.locator('.layout-handle').first.is_visible())
    tile=page.locator('[data-layout-id="kpi-0"]');handle=tile.locator('.layout-handle')
    handle.focus();handle.press('Shift+ArrowRight');handle.press('ArrowRight')
    page.wait_for_timeout(250)
    saved=page.evaluate("JSON.parse(localStorage.getItem('smartvod.panelLayout.v1'))")
    check('Keyboard resize saved',saved['kpi-0']['width']==4)
    check('Keyboard move saved',saved['kpi-0']['order']==1)
    page.reload();page.wait_for_function("applied!==null&&!document.getElementById('apply').disabled",timeout=120000)
    check('Reload restores width',tile.evaluate("e=>e.style.getPropertyValue('--tile-span')")=='4')
    check('Reload restores order',tile.evaluate('e=>e.style.order')=='1')
    check('Reload starts locked',not page.locator('.layout-handle').first.is_visible())
    page.locator('#advancedToggle').click();page.locator('#layoutToggle').click()
    grip=tile.locator('.layout-resize-both');box=grip.bounding_box()
    page.mouse.move(box['x']+15,box['y']+15);page.mouse.down();page.mouse.move(box['x']+115,box['y']+95,steps=10);page.mouse.up();page.wait_for_timeout(250)
    saved=page.evaluate("JSON.parse(localStorage.getItem('smartvod.panelLayout.v1'))")
    check('Pointer resize width',saved['kpi-0']['width']>=5)
    check('Pointer resize height',saved['kpi-0']['height']>140)
    source=page.locator('[data-layout-id="kpi-1"] .layout-handle').bounding_box();target=page.locator('[data-layout-id="average-0"]').bounding_box()
    page.mouse.move(source['x']+50,source['y']+15);page.mouse.down();page.mouse.move(target['x']+50,target['y']+target['height']*.8,steps=15);page.mouse.up();page.wait_for_timeout(250)
    saved=page.evaluate("JSON.parse(localStorage.getItem('smartvod.panelLayout.v1'))")
    check('Pointer move saved',saved['kpi-1']['order']>saved['average-0']['order'])
    before=page.evaluate("JSON.stringify(JSON.parse(localStorage.getItem('smartvod.panelLayout.v1'))['breakdown-0'])")
    page.evaluate('apply()');page.wait_for_function("!document.getElementById('apply').disabled",timeout=120000);page.wait_for_timeout(300)
    check('Query redraw keeps all panels',page.locator('.layout-tile').count()==17)
    check('Breakdown stays editable after redraw',page.locator('[data-layout-id="breakdown-0"] .layout-handle').is_visible())
    page.locator('[data-layout-id="breakdown-0"] .layout-handle').focus();page.keyboard.press('Shift+ArrowRight');page.wait_for_timeout(250)
    page.evaluate('apply()');page.wait_for_function("!document.getElementById('apply').disabled",timeout=120000);page.wait_for_timeout(300)
    check('Resized breakdown survives redraw',page.locator('[data-layout-id="breakdown-0"]').evaluate("e=>e.style.getPropertyValue('--tile-span')")=='4')
    check('Filters unchanged',page.evaluate('JSON.stringify(applied)')==body)
    check('Metrics unchanged',page.locator('#hours').inner_text()==hours)
    for width,height in [(1920,1080),(1024,900),(768,900),(390,844),(320,640)]:
        page.set_viewport_size({'width':width,'height':height});page.wait_for_timeout(100)
        check(str(width)+' no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.set_viewport_size({'width':1440,'height':1000})
    page.locator('#advancedToggle').click();page.locator('#layoutReset').click()
    check('Reset clears stored layout',page.evaluate("localStorage.getItem('smartvod.panelLayout.v1')") is None)
    check('Reset restores widths and automatic heights',tile.evaluate("e=>e.style.getPropertyValue('--tile-span')==='3'&&e.style.getPropertyValue('--tile-height')==='auto'&&e.style.order==='0'"))
    page.locator('#layoutToggle').click();page.locator('#closeAdvanced').click()
    check('Done locks layout',not page.locator('.layout-handle').first.is_visible())
    page.locator('.chart-grid').scroll_into_view_if_needed();page.screenshot(path=str(ROOT/'audit/layout_desktop.png'))
    page.evaluate("localStorage.setItem('smartvod.panelLayout.v1',JSON.stringify({'kpi-0':{width:999,height:-1,order:'bad'}}))")
    page.reload();page.wait_for_function("applied!==null&&!document.getElementById('apply').disabled",timeout=120000)
    check('Invalid saved values fall back safely',tile.evaluate("e=>e.style.getPropertyValue('--tile-span')==='3'"))
    check('No browser errors',not errors)
    browser.close()
(ROOT/'audit/layout.json').write_text(json.dumps({'passed':True,'checks':checks},indent=2))
print('PASS',len(checks),'layout checks')
