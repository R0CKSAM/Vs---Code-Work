"""Human-style expansion walkthrough: five charts, keyboard, mobile, shared state."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent;checks=[]
def check(name,ok):
    assert ok,name
    checks.append(name)
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000});errors=[];queries=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:queries.append(r.url) if r.url.endswith('/api/query') else None)
    page.goto('http://127.0.0.1:8766/')
    page.wait_for_function("applied!==null&&!document.getElementById('apply').disabled",timeout=120000)
    page.evaluate('document.getElementById("start").value=meta.dates.at(-3);renderFilters();void apply()')
    page.wait_for_function("!document.getElementById('apply').disabled",timeout=120000);page.wait_for_timeout(200)
    filters=page.evaluate('JSON.stringify(applied)');layout=page.evaluate("localStorage.getItem('smartvod.panelLayout.v1')");count=len(queries)
    for key in ['watch','device_type','os','region','isp']:
        button=page.locator(f'[data-expand-chart="{key}"]');button.click();dialog=page.locator('.chart-dialog:not(.insight-dialog)');body=page.locator('#expandedChartBody')
        check(key+' expansion opens',dialog.is_visible())
        check(key+' title identifies graph',bool(page.locator('#expandedChartTitle').inner_text()))
        check(key+' applied date scope visible','IST' in page.locator('#expandedChartScope').inner_text())
        check(key+' plot larger than dashboard',body.locator('svg').bounding_box()['height']>400)
        check(key+' current data shown',body.locator('.trend-line').count()>=1)
        legend=body.locator('.trend-legend button');total=legend.count();legend.first.click()
        check(key+' legend selection reflected',body.locator('.trend-line').count()==total-1)
        body.locator('.restore-chart-lines').click();check(key+' show all restores lines',body.locator('.trend-line').count()==total)
        mode='continuous';body.locator(f'[data-mode="{mode}"]').click()
        check(key+' timeline scrolls',body.locator('.trend-viewport').evaluate('e=>e.scrollWidth>e.clientWidth'))
        if key!='watch':
            body.locator('.trend-viewport').evaluate('e=>e.scrollLeft=700');body.locator('.trend-legend button').first.click()
            check(key+' legend toggle preserves timeline position',body.locator('.trend-viewport').evaluate('e=>e.scrollLeft')>=690)
            body.locator('.restore-chart-lines').click()
        viewport=body.locator('.trend-viewport');viewport.focus();page.keyboard.press('End')
        check(key+' keyboard reaches final point',viewport.evaluate('e=>e.scrollLeft')>0 and body.locator('.trend-tooltip').is_visible())
        check(key+' tooltip stays inside expanded body',body.locator('.trend-tooltip').evaluate('e=>e.getBoundingClientRect().right<=e.parentElement.getBoundingClientRect().right+1'))
        page.locator('#closeExpandedChart').focus();page.keyboard.press('Shift+Tab')
        check(key+' Tab stays in chart',page.evaluate('document.activeElement.closest(".chart-dialog")!==null'))
        page.keyboard.press('Escape');check(key+' Escape closes',dialog.is_hidden())
        check(key+' focus returns to source',page.evaluate('document.activeElement.dataset.expandChart')==key)
    check('Expansion uses already loaded results',len(queries)==count)
    check('Applied filters unchanged',page.evaluate('JSON.stringify(applied)')==filters)
    check('Saved panel arrangement unchanged',page.evaluate("localStorage.getItem('smartvod.panelLayout.v1')")==layout)
    page.locator('[data-expand-chart="watch"]').click()
    page.locator('#expandedChartBody [data-mode="compare"]').click()
    check('Comparison chart fits without accidental horizontal scrolling',page.locator('#expandedChartBody .trend-viewport').evaluate('e=>e.scrollWidth<=e.clientWidth+1'))
    for i in range(page.locator('#expandedChartBody .trend-legend button').count()):page.locator('#expandedChartBody .trend-legend button').nth(i).click()
    check('All hidden state is explained','All lines are hidden' in page.locator('#expandedChartBody').inner_text())
    page.locator('#expandedChartBody .restore-chart-lines').click()
    check('Blank chart recoverable',page.locator('#expandedChartBody .trend-line').count()==3)
    page.screenshot(path=str(ROOT/'audit/expanded_watch.png'))
    page.locator('#closeExpandedChart').click()
    page.locator('[data-expand-chart="isp"]').click()
    page.locator('#expandedChartBody [data-mode="totals"]').click()
    check('Expanded totals display all five categories',page.locator('#expandedChartBody .expanded-total-row').count()==5)
    page.locator('#closeExpandedChart').click()
    check('Expand stays available in totals view',page.locator('[data-expand-chart="isp"]').is_visible())
    page.locator('[data-expand-chart="isp"]').click()
    page.locator('#expandedChartBody [data-mode="continuous"]').click()
    check('Expanded ISP names can wrap',page.locator('#expandedChartBody .trend-legend button span').first.evaluate('e=>getComputedStyle(e).whiteSpace==="normal"'))
    for width,height in [(1920,1080),(1024,900),(768,900),(390,844),(320,640),(844,390)]:
        page.set_viewport_size({'width':width,'height':height});page.wait_for_timeout(200)
        box=page.locator('.chart-dialog:not(.insight-dialog)').bounding_box()
        check(f'{width}x{height} dialog contained',box['x']>=0 and box['y']>=0 and box['x']+box['width']<=width+1 and box['y']+box['height']<=height+1)
        check(f'{width}x{height} close stays reachable',page.locator('#closeExpandedChart').bounding_box()['y']<height-44)
        check(f'{width}x{height} no page overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        if width==390:page.screenshot(path=str(ROOT/'audit/expanded_isp_mobile.png'))
    page.locator('#closeExpandedChart').click();check('Close action restores page scrolling',not page.locator('body').evaluate('e=>e.classList.contains("chart-expanded")'))
    check('No JavaScript errors',not errors);browser.close()
(ROOT/'audit/chart_expand.json').write_text(json.dumps({'passed':True,'checks':checks},indent=2))
print('PASS',len(checks),'expanded-chart checks')
