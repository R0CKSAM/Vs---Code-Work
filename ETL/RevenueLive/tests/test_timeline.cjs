'use strict';
const assert=require('node:assert/strict');
const {aggregate}=require('../static/timeline-data.js');
const row=(day,values={})=>({day,channel_id:1,ad:100,other:50,views:10,impressions:5,...values});
const rows=[row('2026-02-20'),row('2026-03-01',{ad:0,other:0}),row('2026-09-29')];
const result=aggregate(rows,{start:'2026-02-20',end:'2026-09-29'});
assert.equal(result.interval,'month');assert.equal(result.buckets.length,8);
assert(result.buckets[0].partial);assert(result.buckets.at(-1).partial);
assert.equal(result.buckets[1].values.ad,0);assert(!result.buckets[1].missing);
assert.equal(result.buckets[2].values.ad,null);assert(result.buckets[2].missing);
for(const key of ['ad','other','views','impressions'])assert.equal(result.buckets.reduce((sum,b)=>sum+(b.values[key]??0),0),rows.reduce((sum,r)=>sum+r[key],0));
assert.equal(aggregate([]).buckets.length,0);
assert.equal(aggregate(rows,{start:'2026-01-01',end:'2026-01-31'}).interval,'day');
assert.equal(aggregate(rows,{start:'2026-01-01',end:'2026-02-01'}).interval,'week');
assert.equal(aggregate(rows,{start:'2026-01-01',end:'2026-04-30'}).interval,'week');
assert.equal(aggregate(rows,{start:'2026-01-01',end:'2026-05-01'}).interval,'month');
const daily=aggregate([row('2026-08-01'),row('2026-08-03',{views:0})],{mode:'day'});
assert.equal(daily.buckets.length,3);assert.equal(daily.buckets[1].values.views,null);assert.equal(daily.buckets[2].values.views,0);
const reverse=aggregate(rows,{start:'2026-09-29',end:'2026-02-20'});
assert.deepEqual(reverse,result);
const weeks=aggregate([row('2026-01-01'),row('2026-01-05')],{mode:'week'});
assert.equal(weeks.buckets[0].periodStart,'2025-12-29');assert.equal(weeks.buckets[0].end,'2026-01-04');
assert.equal(weeks.buckets[1].start,'2026-01-05');
const leap=aggregate([row('2024-02-29')],{start:'2024-02-01',end:'2024-02-29',mode:'month',channelCount:2});
assert.equal(leap.buckets[0].expectedRecords,58);assert.equal(leap.buckets[0].partial,false);assert(leap.buckets[0].incomplete);
const sum=aggregate([row('2026-01-01'),row('2026-01-01',{channel_id:2,views:20})],{mode:'month'});
assert.equal(sum.buckets[0].values.views,30);assert.equal(sum.buckets[0].reportedRecords,2);
const drilled=aggregate(rows,{start:result.buckets[0].start,end:result.buckets[0].end,mode:'day'});
assert.equal(drilled.buckets.reduce((sum,b)=>sum+(b.values.ad??0),0),result.buckets[0].values.ad);
assert.equal(drilled.buckets.length,9);
console.log('Timeline: auto thresholds, calendar boundaries, partial periods, null gaps, zero values, totals, coverage and drill-down PASS');
