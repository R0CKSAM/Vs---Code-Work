def generate_report(result: DiscoveryResult, output_path: str = "docs/discovery.md") -> Path:
    """
    Generate a discovery report from a DiscoveryResult and write it to *output_path*.
    """
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)

    report = _build_report(result)
    out.write_text(report, encoding="utf-8")
    return out


def _build_report(result: DiscoveryResult) -> str:
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    # Page table
    page_rows = []
    for i, p in enumerate(result.pages, 1):
        title_short = (p.title or "")[:60].replace("|", "/")
        url_short = p.url[:80]
        page_rows.append(
            f"| {i} | `{url_short}` | {p.page_type.value} | {p.depth} "
            f"| {p.http_status or 'N/A'} | {title_short} |"
        )
    page_table = "\n".join(page_rows) if page_rows else "| — | No pages discovered | — | — | — | — |"

    # Classification table
    type_counts = Counter(p.page_type.value for p in result.pages)
    cls_rows = [f"| {t} | {c} |" for t, c in sorted(type_counts.items())]
    classification_table = "\n".join(cls_rows) or "| UNKNOWN | 0 |"

    # URL patterns
    all_urls = [p.url for p in result.pages]
    patterns = _extract_url_patterns(all_urls)
    url_patterns = "\n".join(patterns) if patterns else "No patterns identified."

    # JSON endpoints
    json_eps = result.json_endpoints
    if json_eps:
        ep_lines = []
        seen = set()
        for ep in json_eps[:30]:  # cap to 30 unique for readability
            key = ep.url[:120]
            if key not in seen:
                seen.add(key)
                ep_lines.append(
                    f"- [{ep.method}] `{ep.url[:120]}` "
                    f"(status={ep.status}, type={ep.resource_type})"
                )
        json_endpoints_section = "\n".join(ep_lines)
    else:
        json_endpoints_section = "> No JSON endpoints were observed during this discovery run.\n> This may indicate the site loads data via server-side rendering."

    # Resource type breakdown
    type_counter = Counter(e.resource_type for e in result.all_network_events)
    rt_rows = [f"| {t} | {c} |" for t, c in sorted(type_counter.items(), key=lambda x: -x[1])]
    resource_type_table = "\n".join(rt_rows) or "| — | 0 |"

    # Unique links
    all_internal_links = []
    for p in result.pages:
        all_internal_links.extend(p.internal_links)
    unique_links = list(dict.fromkeys(all_internal_links))
    sample_links = "\n".join(unique_links[:30]) if unique_links else "None discovered."

    # Image patterns
    all_images = []
    for p in result.pages:
        all_images.extend(p.image_urls[:3])
    image_patterns = "\n".join(list(dict.fromkeys(all_images))[:15]) if all_images else "No image URLs sampled."

    # Dynamic behavior
    has_fetch = any(e.resource_type == "fetch" for e in result.all_network_events)
    has_xhr = any(e.resource_type == "xhr" for e in result.all_network_events)
    dynamic_lines = [
        f"- **fetch requests observed**: {'Yes [OBSERVED]' if has_fetch else 'No'}",
        f"- **XHR requests observed**: {'Yes [OBSERVED]' if has_xhr else 'No'}",
        f"- **JSON API responses observed**: {'Yes [OBSERVED]' if json_eps else 'No'}",
        "- **Infinite scroll**: Not tested in this run [UNKNOWN]",
        "- **Load-more buttons**: Not tested in this run [UNKNOWN]",
        "- **Pagination**: Not tested in this run [UNKNOWN]",
    ]
    dynamic_behavior = "\n".join(dynamic_lines)

    # Recommendations
    rec_lines = [
        "- [RECOMMENDED] Use headless Chromium (Playwright) for scraping — site is JS-rendered.",
        "- [RECOMMENDED] Apply REQUEST_DELAY_SECONDS between page visits to be polite.",
        f"- [OBSERVED] {len(all_urls)} pages are publicly accessible without authentication.",
        "- [RECOMMENDED] Start with schedule/live pages for time-sensitive data.",
    ]
    if json_eps:
        rec_lines.append("- [OBSERVED] JSON API endpoints are available — consider monitoring these directly in later phases.")
    else:
        rec_lines.append("- [OBSERVED] No JSON API responses seen — rely on DOM extraction in later phases.")
    recommendations = "\n".join(rec_lines)

    # Limitations
    limitations = (
        f"- Discovery was limited to {result.page_count} pages "
        f"(DISCOVERY_MAX_PAGES={len(result.pages)}).\n"
        "- Dynamic content (infinite scroll, lazy loading) was not fully explored.\n"
        "- Only publicly accessible pages were visited.\n"
        "- Network body content was NOT captured (only metadata).\n"
        "- Authentication-gated content was not accessed.\n"
        f"- Terminated early: {result.terminated_early} "
        f"({result.termination_reason or 'N/A'})."
    )

    status = "COMPLETE" if not result.terminated_early else f"PARTIAL — {result.termination_reason}"
    term_note = f"({result.termination_reason})" if result.terminated_early else ""

    return _REPORT_TEMPLATE.format(
        generated_at=generated_at,
        status=status,
        base_url=result.base_url,
        page_count=result.page_count,
        terminated_early=result.terminated_early,
        termination_reason=term_note,
        page_table=page_table,
        classification_table=classification_table,
        url_patterns=url_patterns,
        total_network_events=len(result.all_network_events),
        json_endpoint_count=len(json_eps),
        json_endpoints_section=json_endpoints_section,
        resource_type_table=resource_type_table,
        unique_links_count=len(unique_links),
        sample_links=sample_links,
        image_patterns=image_patterns,
        dynamic_behavior=dynamic_behavior,
        recommendations=recommendations,
        limitations=limitations,
        output_dir=str(Path(settings.DISCOVERY_OUTPUT_DIR).resolve()),
    )


def _extract_url_patterns(urls: list[str]) -> list[str]:
    """Derive simple structural URL patterns from a list of URLs."""
    from urllib.parse import urlparse
    from collections import Counter

    path_prefixes: Counter = Counter()
    for url in urls:
        path = urlparse(url).path or "/"
        parts = [p for p in path.split("/") if p]
        if not parts:
            path_prefixes["/ (root/home)"] += 1
        else:
            path_prefixes[f"/{parts[0]}/..."] += 1

    patterns = []
    for prefix, count in path_prefixes.most_common():
        patterns.append(f"  {prefix}  ({count} pages)")
    return patterns
